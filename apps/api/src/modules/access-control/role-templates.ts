/**
 * System role templates (RBAC.md §7–§33). Templates are read-only, tenant-independent
 * (`roles.tenant_id IS NULL`) and synchronized from this file at startup. Assigning a template
 * grants its permissions only inside the membership's tenant (P3-D6).
 *
 * Where RBAC.md lists "additional permissions" or "inherits" another role, the base role's
 * permissions are listed explicitly — there is no implicit hierarchy (RBAC.md §53).
 */
export interface RoleTemplate {
  key: string;
  name: string;
  level: 'PLATFORM' | 'TENANT';
  description: string;
  permissions: readonly string[];
}

